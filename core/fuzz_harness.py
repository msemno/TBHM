"""Generate reviewable fuzzing harnesses and seed corpora from normalized IR."""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Iterable

PARSER_NAME = re.compile(r"(?i)(parse|decode|deserialize|unpack|process|handle|consume|read|load|import|receive|packet|message|frame|request)")
POINTER_TYPE = re.compile(r"(?i)(\*|char\s*\*|void\s*\*|uint8_t\s*\*|byte\[|buffer|ptr)")
LENGTH_TYPE = re.compile(r"(?i)(size_t|length|len|count|uint\d+_t|int|long)")
TOKEN_RE = re.compile(r"[A-Za-z][A-Za-z0-9_./:\-]{2,80}")


def _param_type(param) -> str:
    if isinstance(param, dict):
        return str(param.get("type") or param.get("datatype") or param.get("data_type") or "")
    return str(param)


def candidate_functions(ir: dict, max_functions: int = 100) -> list[dict]:
    candidates = []
    for fn in ir.get("functions", []):
        if not isinstance(fn, dict) or fn.get("external"):
            continue
        name = str(fn.get("name") or "")
        params = fn.get("parameters") if isinstance(fn.get("parameters"), list) else []
        types = [_param_type(x) for x in params]
        score, reasons = 0, []
        if PARSER_NAME.search(name):
            score += 5; reasons.append("parser-like function name")
        if types and POINTER_TYPE.search(types[0]):
            score += 4; reasons.append("first parameter is buffer-like")
        if len(types) >= 2 and LENGTH_TYPE.search(types[1]):
            score += 3; reasons.append("second parameter is length-like")
        pcode = fn.get("pcode") if isinstance(fn.get("pcode"), list) else []
        calls = " ".join(str(op.get("callee") or "") for op in pcode if isinstance(op, dict))
        if re.search(r"(?i)(memcpy|strcpy|sprintf|read|recv|uncompress|inflate)", calls):
            score += 3; reasons.append("calls parser/memory primitives")
        if score >= 5:
            candidates.append({"function": fn, "score": score, "reasons": reasons})
    candidates.sort(key=lambda row: (-row["score"], str(row["function"].get("name"))))
    return candidates[:max(1, min(max_functions, 1000))]


def _safe_c_name(value: str) -> str:
    value = re.sub(r"\W+", "_", value).strip("_")
    if not value or value[0].isdigit():
        value = "fn_" + value
    return value[:120]


def generate_harness(ir: dict, function: dict, out_dir: str | Path) -> dict:
    out_dir = Path(out_dir)
    name = str(function.get("name") or "target")
    c_name = _safe_c_name(name)
    target = out_dir / c_name
    target.mkdir(parents=True, exist_ok=True)
    params = function.get("parameters") if isinstance(function.get("parameters"), list) else []
    types = [_param_type(x) for x in params]
    signature_supported = bool(types and POINTER_TYPE.search(types[0]) and (len(types) == 1 or LENGTH_TYPE.search(types[1])))
    prototype = f"extern int {c_name}(const uint8_t *data, size_t size);"
    call = f"(void){c_name}(Data, Size);"
    if len(types) == 1:
        prototype = f"extern int {c_name}(const uint8_t *data);"
        call = f"(void){c_name}(Data);"
    code = f'''// Generated by TBHM. Review the recovered prototype and initialization before compiling.
#include <stddef.h>
#include <stdint.h>
#include <stdlib.h>

{prototype}

int LLVMFuzzerTestOneInput(const uint8_t *Data, size_t Size) {{
    if (Data == NULL || Size == 0 || Size > (1u << 20)) return 0;
    {call}
    return 0;
}}
'''
    (target / "harness.c").write_text(code, encoding="utf-8")
    (target / "README.md").write_text(
        "# Generated fuzz harness\n\n"
        f"Function: `{name}`\n\n"
        "The prototype is inferred and must be verified against decompiler output. "
        "Initialization, global state, allocators, and cleanup are not guessed. Compile and execute only in an isolated environment.\n",
        encoding="utf-8",
    )
    tokens = set()
    for value in function.get("strings", []):
        text = str(value.get("value") or value) if isinstance(value, dict) else str(value)
        tokens.update(TOKEN_RE.findall(text))
    dictionary = "\n".join(f'token_{i}="{token.replace(chr(34), r"\"")}"' for i, token in enumerate(sorted(tokens)[:1000]))
    (target / "dictionary.txt").write_text(dictionary + ("\n" if dictionary else ""), encoding="utf-8")
    manifest = {
        "function": name, "start": function.get("start"), "fingerprint": function.get("fingerprint"),
        "parameter_types": types, "signature_supported": signature_supported,
        "harness": str(target / "harness.c"), "dictionary": str(target / "dictionary.txt"),
        "execution_performed": False, "confirmation_state": "generated_proposal",
    }
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return manifest


def generate_all(ir: dict, out_dir: str | Path, max_functions: int = 50) -> dict:
    candidates = candidate_functions(ir, max_functions=max_functions)
    manifests = [generate_harness(ir, row["function"], out_dir) | {"score": row["score"], "reasons": row["reasons"]}
                 for row in candidates]
    return {"schema": "tbhm.fuzz-harness/1.0", "generated": manifests, "count": len(manifests),
            "execution_performed": False}
