#!/usr/bin/env python3
"""Build the complete TBHM v3.9.7.5 release manifest.

The manifest intentionally excludes only itself, generated bytecode/caches,
version-control metadata and runtime result directories.  Every other packaged
file must be listed so core.package_verifier can enforce inventory equality.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

RELEASE = "3.9.7.5-universal-deep-reverse"
ROOT_NAME = "TBHM-v3.9.7.5-FULL"
DEFAULT_OUTPUT = "RELEASE_MANIFEST-v3.9.7.5.json"
EXCLUDED_DIRS = {"__pycache__", ".git", ".pytest_cache", ".mypy_cache", ".ruff_cache", "results"}
EXCLUDED_SUFFIXES = {".pyc", ".pyo", ".swp", ".tmp"}
EXCLUDED_NAMES = {".DS_Store"}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def release_files(root: Path, output_name: str):
    for path in sorted(root.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        rel = path.relative_to(root)
        if any(part in EXCLUDED_DIRS for part in rel.parts):
            continue
        if path.suffix in EXCLUDED_SUFFIXES or path.name in EXCLUDED_NAMES or path.name == output_name:
            continue
        yield path


def cli_flags(path: Path) -> set[str]:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8", errors="strict"))
    except (OSError, SyntaxError, UnicodeError):
        return set()
    values = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        if node.func.attr != "add_argument":
            continue
        for arg in node.args:
            if isinstance(arg, ast.Constant) and isinstance(arg.value, str) and arg.value.startswith("-"):
                values.add(arg.value)
    return values


def phase_names(path: Path) -> list[str]:
    tree = ast.parse(path.read_text(encoding="utf-8", errors="strict"))
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == "PHASE_ORDER" for t in node.targets):
            result = ast.literal_eval(node.value)
            return list(result) if isinstance(result, list) else []
    return []


def generated_at() -> str:
    source_epoch = os.environ.get("SOURCE_DATE_EPOCH", "").strip()
    if source_epoch:
        return datetime.fromtimestamp(int(source_epoch), timezone.utc).isoformat(timespec="seconds")
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def build(root: Path, output: Path) -> dict:
    rows = []
    extension_counts = Counter()
    project_flags = set()
    for path in release_files(root, output.name):
        rel = path.relative_to(root).as_posix()
        suffix = path.suffix.lower().lstrip(".") or "no_extension"
        extension_counts[suffix] += 1
        executable = bool(path.stat().st_mode & 0o111)
        rows.append({
            "path": rel,
            "size": path.stat().st_size,
            "sha256": sha256(path),
            "executable": executable,
            "type": suffix,
        })
        if path.suffix == ".py":
            project_flags.update(cli_flags(path))
    primary_flags = sorted(cli_flags(root / "tbhm.py"))
    phases = phase_names(root / "tbhm.py")
    return {
        "schema": "tbhm-release-manifest/v1",
        "release": RELEASE,
        "semantic_version": "3.9.7.5",
        "generated_at": generated_at(),
        "root_name": ROOT_NAME,
        "manifest_policy": "Lists every packaged regular file except this manifest; symlinks, caches, bytecode, VCS metadata and runtime results are excluded.",
        "summary": {
            "files": len(rows),
            "bytes": sum(row["size"] for row in rows),
            "primary_cli_option_strings": len(primary_flags),
            "project_wide_cli_option_strings": len(project_flags),
            "phase_modules": len(phases),
            "executable_files": sum(1 for row in rows if row["executable"]),
        },
        "counts_by_extension": dict(sorted(extension_counts.items())),
        "primary_cli_options": primary_flags,
        "project_wide_cli_option_strings": sorted(project_flags),
        "phase_modules": phases,
        "compatibility": {
            "v3.9.7.3_cli_options_removed": 0,
            "v3.9.7.3_phases_removed": 0,
            "v3.9.7.4_cli_options_removed": 0,
            "v3.9.7.4_phases_removed": 0,
            "intentional_safety_change": "EMBA emulation/full requires a prepared sandbox image; confirmation alone no longer permits host emulation.",
        },
        "files": rows,
        "notes": [
            "RouterSploit is catalog/import-only and no active RouterSploit module is launched.",
            "EMBA host execution is limited to static/SBOM; emulation/full requires an already-present sandbox image and explicit confirmation.",
            "Ghidra, angr, EMBA, QEMU, UEFI, mobile and protocol tools remain separately installed external runtimes.",
            "Static paths, imported output, CVE references and crashes are not automatically confirmed vulnerabilities.",
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default=str(Path(__file__).resolve().parents[1]))
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    root = Path(args.root).expanduser().resolve(strict=True)
    output = Path(args.output)
    if not output.is_absolute():
        output = root / output
    data = build(root, output)
    output.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"wrote {output} ({data['summary']['files']} files)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
