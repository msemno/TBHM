"""
Phase: vuln_scan_extended

Adds to existing vuln_scan with:
  1. retire.js — JS library vulnerability scanner (huge value for SPAs)
  2. dalfox    — focused XSS scanner (better than nuclei for parameter XSS)
  3. nuclei    — Atlassian / WordPress / Jenkins / GitLab tech-specific templates
  4. nuclei    — Apache / nginx / IIS server-specific CVE templates
  5. wpscan    — WordPress-specific scanner (auto-runs if WP detected)

Each tool's findings are normalized into TBHM findings with curl reproducers
auto-generated by storage.save_finding.
"""
from __future__ import annotations
from core import ratelimit
import json
import re
import shutil
import subprocess
from pathlib import Path
from urllib.parse import urlparse

from core import anti_block, noise_filter
from core.targets import get_root_domains


def run(ctx):
    # Build targets list
    alive_file = ctx.output / "recon" / "alive.txt"
    if not alive_file.exists():
        ctx.log("WARN", "vuln_scan_extended", "no alive.txt — skipping")
        return
    alive = ctx.runner.read_lines(alive_file)
    in_scope = set(get_root_domains(ctx))
    alive = [u for u in alive if not noise_filter.is_noise(u, in_scope_hosts=in_scope)[0]]
    if not alive:
        return

    intensity = getattr(ctx, "intensity", "standard")
    timeout_min = {"quick": 3, "standard": 8, "deep": 20, "insane": 35}.get(intensity, 8)

    out_dir = ctx.output / "vuln_scan_ext"
    out_dir.mkdir(exist_ok=True)

    n_total = 0
    n_total += _run_retire_js(ctx, alive, out_dir, timeout_min)
    n_total += _run_dalfox(ctx, alive, out_dir, timeout_min)
    n_total += _run_nuclei_tech_stack(ctx, alive, out_dir, timeout_min, intensity)
    n_total += _run_nuclei_atlassian(ctx, alive, out_dir, timeout_min)
    n_total += _run_wpscan_if_wp(ctx, alive, out_dir, timeout_min)

    ctx.log("OK", "vuln_scan_extended",
            f"vuln_scan_extended: {n_total} findings")


# ──────────────────────────────────────────────────────────────────────────────
# 1. retire.js — JS library CVE scanner
# ──────────────────────────────────────────────────────────────────────────────
def _run_retire_js(ctx, targets: list[str], out_dir: Path, timeout_min: int) -> int:
    if not shutil.which("retire"):
        ctx.log("INFO", "vuln_scan_extended",
                "  retire.js not installed — skip (npm i -g retire)")
        return 0

    out_file = out_dir / "retire.json"
    ctx.log("INFO", "vuln_scan_extended", "  → retire.js (JS library CVEs)")

    n = 0
    for url in targets[:30]:
        try:
            r = subprocess.run(
                ["retire", "--outputformat", "json", "--outputpath", str(out_file),
                 "--js", "--exitwith", "0",
                 "--jspath", url],
                capture_output=True, text=True, timeout=timeout_min * 60
            )
        except subprocess.TimeoutExpired:
            continue
        except Exception:
            continue
        if not out_file.exists():
            continue
        try:
            data = json.loads(out_file.read_text())
        except Exception:
            continue
        for entry in data.get("data", []) if isinstance(data, dict) else data:
            for r_item in entry.get("results", []):
                lib  = r_item.get("component", "?")
                ver  = r_item.get("version", "?")
                for vuln in r_item.get("vulnerabilities", []):
                    sev = (vuln.get("severity") or "low").upper()
                    severity = {"LOW": "LOW", "MEDIUM": "MEDIUM",
                                "HIGH": "HIGH", "CRITICAL": "CRITICAL"}.get(sev, "LOW")
                    cves = ", ".join(vuln.get("identifiers", {}).get("CVE", []))
                    summary = vuln.get("identifiers", {}).get("summary", "")
                    ctx.save_finding({
                        "phase": "vuln_scan_extended", "severity": severity,
                        "confidence": "HIGH",
                        "title": f"[retire.js] {lib} {ver} — {cves or 'vulnerable version'}",
                        "target": urlparse(url).hostname, "url": url,
                        "evidence": f"Library: {lib} v{ver}. CVEs: {cves}. {summary}",
                        "description": (
                            f"The page loads a vulnerable version of {lib}. "
                            f"Known CVEs: {cves}"
                        ),
                        "impact": vuln.get("identifiers", {}).get("summary", "")
                                  or "See linked CVEs for exploitation details.",
                        "remediation": f"Upgrade {lib} to the latest version.",
                        "cwe": "CWE-1395",
                        "references": vuln.get("info", []),
                        "mrs_score": {"CRITICAL": 90, "HIGH": 75,
                                      "MEDIUM": 55, "LOW": 35}.get(severity, 35),
                    })
                    n += 1
    ctx.log("OK", "vuln_scan_extended", f"  retire.js: {n} findings")
    return n


# ──────────────────────────────────────────────────────────────────────────────
# 2. dalfox — XSS focused scanner
# ──────────────────────────────────────────────────────────────────────────────
def _run_dalfox(ctx, targets: list[str], out_dir: Path, timeout_min: int) -> int:
    if not shutil.which("dalfox"):
        ctx.log("INFO", "vuln_scan_extended",
                "  dalfox not installed — skip (go install github.com/hahwul/dalfox/v2@latest)")
        return 0

    ctx.log("INFO", "vuln_scan_extended", "  → dalfox (XSS specialist)")

    # Build URL list — only URLs with parameters
    params_urls = []
    for u in targets:
        if "?" in u and "=" in u.split("?", 1)[1]:
            params_urls.append(u)
    if not params_urls:
        ctx.log("INFO", "vuln_scan_extended", "  dalfox: no URLs with params")
        return 0

    in_file = out_dir / "dalfox_targets.txt"
    in_file.write_text("\n".join(params_urls[:200]))
    out_file = out_dir / "dalfox.json"

    try:
        r = subprocess.run(
            ["dalfox", "file", str(in_file),
             "--format", "json", "--output", str(out_file),
             "--silence", "--worker", "30",
             "--skip-bav", "--skip-mining-all", "--no-color"],
            capture_output=True, text=True, timeout=timeout_min * 60
        )
    except subprocess.TimeoutExpired:
        ctx.log("WARN", "vuln_scan_extended", "  dalfox: timeout")
        return 0
    except Exception as e:
        ctx.log("WARN", "vuln_scan_extended", f"  dalfox error: {e}")
        return 0

    if not out_file.exists():
        return 0
    n = 0
    for line in out_file.read_text(errors="ignore").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except Exception:
            continue
        url = obj.get("target", "") or obj.get("url", "")
        if not url:
            continue
        param = obj.get("param", "")
        payload = obj.get("payload", "")
        ctx.save_finding({
            "phase": "vuln_scan_extended", "severity": "HIGH",
            "confidence": "HIGH",
            "title": f"[dalfox] Reflected XSS via parameter '{param}'",
            "target": urlparse(url).hostname, "url": url, "method": "GET",
            "parameter": param, "payload": payload,
            "evidence": f"dalfox payload: {payload}",
            "description": "dalfox confirmed reflected XSS — payload executed in browser.",
            "impact": "Account takeover via session hijacking, credential theft, "
                     "phishing redirects.",
            "remediation": "Context-aware output encoding. Set strict CSP. "
                          "Validate input on the server side.",
            "cwe": "CWE-79", "mrs_score": 85,
        })
        n += 1
    ctx.log("OK", "vuln_scan_extended", f"  dalfox: {n} findings")
    return n


# ──────────────────────────────────────────────────────────────────────────────
# 3. nuclei — tech-stack templates (WP, Jenkins, GitLab, etc)
# ──────────────────────────────────────────────────────────────────────────────
def _run_nuclei_tech_stack(ctx, targets: list[str], out_dir: Path,
                            timeout_min: int, intensity: str) -> int:
    if not shutil.which("nuclei"):
        return 0
    in_file = out_dir / "nuclei_targets.txt"
    in_file.write_text("\n".join(targets[:300]))

    rate_limit = ratelimit.cap(ctx.profile, {"quick": 30, "standard": 75, "deep": 150, "insane": 300}.get(intensity, 75))
    out_file = out_dir / "nuclei_tech.jsonl"

    ctx.log("INFO", "vuln_scan_extended", "  → nuclei (tech-stack templates)")
    try:
        subprocess.run(
            ["nuclei", "-l", str(in_file),
             "-jsonl", "-o", str(out_file),
             "-rl", str(rate_limit), "-silent",
             "-tags",
             "wordpress,jenkins,gitlab,kubernetes,docker,grafana,kibana,"
             "elasticsearch,mongodb,redis,prometheus,nagios,zabbix,jira,"
             "confluence,bitbucket,sonarqube,gitea,jfrog,nexus",
             "-severity", "low,medium,high,critical",
             "-disable-update-check"],
            capture_output=True, text=True, timeout=timeout_min * 60
        )
    except subprocess.TimeoutExpired:
        ctx.log("WARN", "vuln_scan_extended", "  nuclei tech-stack: timeout")
    except Exception as e:
        ctx.log("WARN", "vuln_scan_extended", f"  nuclei error: {e}")
        return 0

    return _ingest_nuclei_jsonl(ctx, out_file, "tech-stack")


# ──────────────────────────────────────────────────────────────────────────────
# 4. nuclei — Atlassian-specific (CVEs + misconfigs)
# ──────────────────────────────────────────────────────────────────────────────
def _run_nuclei_atlassian(ctx, targets: list[str], out_dir: Path, timeout_min: int) -> int:
    if not shutil.which("nuclei"):
        return 0
    # Only run on hosts that look like Atlassian
    atlassian_hosts = [t for t in targets
                       if any(s in t.lower()
                              for s in ("atlassian", "jira", "confluence",
                                        "bitbucket", "servicedesk"))]
    if not atlassian_hosts:
        return 0

    in_file = out_dir / "atlassian_targets.txt"
    in_file.write_text("\n".join(atlassian_hosts[:100]))
    out_file = out_dir / "nuclei_atlassian.jsonl"

    ctx.log("INFO", "vuln_scan_extended",
            f"  → nuclei (Atlassian-specific, {len(atlassian_hosts)} hosts)")
    try:
        subprocess.run(
            ["nuclei", "-l", str(in_file),
             "-jsonl", "-o", str(out_file),
             "-rl", "50", "-silent",
             "-tags", "atlassian,jira,confluence,bitbucket",
             "-severity", "info,low,medium,high,critical",
             "-disable-update-check"],
            capture_output=True, text=True, timeout=timeout_min * 60
        )
    except Exception as e:
        ctx.log("WARN", "vuln_scan_extended", f"  nuclei atlassian error: {e}")
        return 0

    return _ingest_nuclei_jsonl(ctx, out_file, "atlassian-specific")


# ──────────────────────────────────────────────────────────────────────────────
# 5. wpscan — if WordPress detected
# ──────────────────────────────────────────────────────────────────────────────
def _run_wpscan_if_wp(ctx, targets: list[str], out_dir: Path, timeout_min: int) -> int:
    if not shutil.which("wpscan"):
        return 0
    # Detect WP via /wp-content or X-Powered-By
    wp_hosts = []
    for t in targets[:30]:
        try:
            import requests
            r = requests.get(t, timeout=8, verify=False,
                             headers=anti_block.headers_for(urlparse(t).hostname))
            if "wp-content" in r.text or "wordpress" in r.text.lower()[:5000]:
                wp_hosts.append(t)
        except Exception:
            continue

    if not wp_hosts:
        return 0
    ctx.log("INFO", "vuln_scan_extended",
            f"  → wpscan ({len(wp_hosts)} WordPress hosts)")

    n = 0
    for url in wp_hosts:
        out_file = out_dir / f"wpscan_{urlparse(url).hostname}.json"
        try:
            subprocess.run(
                ["wpscan", "--url", url, "-o", str(out_file),
                 "-f", "json", "--no-update", "--random-user-agent"],
                capture_output=True, text=True, timeout=timeout_min * 60
            )
        except Exception:
            continue
        if not out_file.exists():
            continue
        try:
            data = json.loads(out_file.read_text())
        except Exception:
            continue
        # WP version vulns
        version = data.get("version", {})
        for vuln in version.get("vulnerabilities", []) if version else []:
            ctx.save_finding({
                "phase": "vuln_scan_extended", "severity": "HIGH",
                "confidence": "HIGH",
                "title": f"[wpscan] WordPress {version.get('number','?')} — {vuln.get('title','?')}",
                "target": urlparse(url).hostname, "url": url,
                "evidence": f"WordPress {version.get('number','?')}: {vuln.get('title','?')}",
                "description": vuln.get("title", ""),
                "remediation": "Upgrade WordPress core to the latest version.",
                "cwe": "", "mrs_score": 80,
            })
            n += 1
    ctx.log("OK", "vuln_scan_extended", f"  wpscan: {n} findings")
    return n


# ──────────────────────────────────────────────────────────────────────────────
# Helper — ingest nuclei JSONL
# ──────────────────────────────────────────────────────────────────────────────
def _ingest_nuclei_jsonl(ctx, out_file: Path, label: str) -> int:
    if not out_file.exists():
        return 0
    n = 0
    for line in out_file.read_text(errors="ignore").splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            obj = json.loads(line)
        except Exception:
            continue
        info = obj.get("info") or {}
        template_id = obj.get("template-id") or obj.get("templateID", "")
        matched_at = obj.get("matched-at") or obj.get("matchedAt", "")
        if not matched_at or not template_id:
            continue
        severity = (info.get("severity") or "info").upper()
        sev = {"INFO": "INFO", "LOW": "LOW", "MEDIUM": "MEDIUM",
               "HIGH": "HIGH", "CRITICAL": "CRITICAL"}.get(severity, "LOW")
        ctx.save_finding({
            "phase": "vuln_scan_extended", "severity": sev, "confidence": "HIGH",
            "title": f"[{label}] {info.get('name', template_id)}",
            "target": urlparse(matched_at).hostname, "url": matched_at,
            "method": (obj.get("request", "") or "GET").split(" ", 1)[0],
            "description": info.get("description", "") or f"nuclei template: {template_id}",
            "evidence": (" | ".join(obj.get("extracted-results", []))
                        if obj.get("extracted-results")
                        else obj.get("matcher-name", "")),
            "remediation": info.get("remediation", "") or "See nuclei template.",
            "cwe": (info.get("classification", {}) or {}).get("cwe-id", "") or "",
            "cvss": str((info.get("classification", {}) or {}).get("cvss-score", "")),
            "references": info.get("reference") or [],
            "request_raw": (obj.get("request") or "")[:8000],
            "response_raw": (obj.get("response") or "")[:8000],
            "mrs_score": {"CRITICAL": 90, "HIGH": 75, "MEDIUM": 55,
                          "LOW": 35, "INFO": 20}.get(sev, 35),
        })
        n += 1
    ctx.log("OK", "vuln_scan_extended", f"  nuclei {label}: {n} findings")
    return n
